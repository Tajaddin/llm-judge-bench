def builtin_pairs() -> list[JudgePair]:
    return [
        JudgePair(
            item_id=f"q{i+1:02d}",
            question=q,
            candidate_a=a,
            candidate_b=b,
            gold_winner=gw,
        )
        for i, (q, a, b, gw) in enumerate(_BANK)
    ]
